// Rodada 13 (achado da lente L1, PR #757) — a seleção automática do tornado
// pula a alavanca circular mesmo quando ela tem a maior amplitude. Ver o
// cabeçalho de `casos/cenarios-tornado-pula-circular.ts`.

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { verificarRender } from '../../scripts/render-check.mjs';
import {
  contar, declaracoesOciosas, larguraComOverflowDeDocumento, naoDeclaradas, motivoParaPular, relato,
} from './apoio.js';

const pular = await motivoParaPular();

test('Cenários: a seleção automática pula a alavanca circular mesmo com a maior amplitude', { skip: pular ?? false }, async () => {
  const a = await verificarRender({ caso: 'cenarios-tornado-pula-circular' });

  assert.deepEqual(a.montagem?.faltando ?? [], [], 'a seleção pulando a circular não chegou ao DOM' + relato(a));
  assert.equal(contar(a, 'transbordoDeCaixa'), 0, 'caixa transbordou' + relato(a));
  assert.equal(contar(a, 'sobreposicao'), 0, 'caixa sobre caixa' + relato(a));
  assert.deepEqual(larguraComOverflowDeDocumento(a), [], 'o documento rolou na horizontal' + relato(a));
  assert.deepEqual(a.erroConsole, [], 'a página lançou erro durante a montagem' + relato(a));
  assert.deepEqual(naoDeclaradas(a), [], 'prop que o stub não reproduz, em uso e não declarada' + relato(a));
  assert.deepEqual(declaracoesOciosas(a), [], 'declaração ociosa em aceitaNaoReproduzido' + relato(a));
  assert.equal(a.montagem?.assentou, true, 'o Lit não assentou antes da medição' + relato(a));
});
